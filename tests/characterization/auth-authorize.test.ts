import { beforeEach, describe, expect, it, vi } from "vitest";

import type { User } from "@/server/db/schema";

type CredentialsInput = { email: string; password: string };

type AuthorizedUser = {
  id: string;
  email: string;
  type: string;
  emailVerified: boolean;
  hasActiveSubscription: boolean;
  isTester: boolean;
};

type CredentialsProviderOptions = {
  authorize: (credentials: CredentialsInput) => Promise<AuthorizedUser | null>;
};

type CapturedAuthConfig = {
  providers: CredentialsProviderOptions[];
};

const {
  captured,
  compareMock,
  getActiveUserSubscriptionMock,
  getUserByEmailMock,
} = vi.hoisted(() => ({
  captured: { config: undefined as CapturedAuthConfig | undefined },
  compareMock: vi.fn<(password: string, hash: string) => Promise<boolean>>(),
  getActiveUserSubscriptionMock:
    vi.fn<(input: { userId: string }) => Promise<{ id: string } | null>>(),
  getUserByEmailMock: vi.fn<(email: string) => Promise<User | null>>(),
}));

// NextAuth() is replaced by a stub that keeps the config it was called with,
// so the real `authorize` from the app's auth module can be invoked directly.
vi.mock("next-auth", () => ({
  default: (config: CapturedAuthConfig) => {
    captured.config = config;
    return { handlers: {}, auth: vi.fn(), signIn: vi.fn(), signOut: vi.fn() };
  },
  // The auth module extends this class for its rate-limit error.
  CredentialsSignin: class CredentialsSignin extends Error {
    code = "credentials";
  },
}));
vi.mock("next-auth/providers/credentials", () => ({
  default: (options: CredentialsProviderOptions) => options,
}));
vi.mock("@/server/modules/auth/secret", () => ({
  getAuthSecret: () => "test-auth-secret",
}));
// Only `compare` is replaced: the dummy password hash is still generated by
// the real bcrypt when the constants module loads.
vi.mock("bcrypt-ts", async () => {
  const actual = await vi.importActual<typeof import("bcrypt-ts")>("bcrypt-ts");
  return { ...actual, compare: compareMock };
});
vi.mock("@/lib/db/query/subscription/get-active-user-subscription", () => ({
  getActiveUserSubscription: getActiveUserSubscriptionMock,
}));
vi.mock("@/server/modules/users/queries/get-by-email", () => ({
  getUserByEmail: getUserByEmailMock,
}));

await import("./targets/auth-config");

const USER_ID = "user-1";
const USER_EMAIL = "user@example.test";
const PASSWORD = "typed-password";
const STORED_PASSWORD_HASH = "stored-password-hash";
const BCRYPT_HASH_PATTERN = /^\$2[aby]\$\d{2}\$/;

const userRow = (overrides: Partial<User> = {}): User =>
  ({
    id: USER_ID,
    email: USER_EMAIL,
    password: STORED_PASSWORD_HASH,
    emailVerified: true,
    isTester: false,
    ...overrides,
  }) as User;

const runAuthorize = (
  credentials: CredentialsInput
): Promise<AuthorizedUser | null> => {
  const provider = captured.config?.providers[0];
  if (!provider) {
    throw new Error("The auth module did not register a credentials provider");
  }
  return provider.authorize(credentials);
};

describe("credentials authorize", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    compareMock.mockResolvedValue(true);
    getUserByEmailMock.mockResolvedValue(userRow());
    getActiveUserSubscriptionMock.mockResolvedValue(null);
  });

  it("returns null for an unknown email after one compare against the dummy hash", async () => {
    // Arrange
    getUserByEmailMock.mockResolvedValue(null);

    // Act
    const authorizedUser = await runAuthorize({
      email: USER_EMAIL,
      password: PASSWORD,
    });

    // Assert
    expect(authorizedUser).toBeNull();
    expect(compareMock).toHaveBeenCalledTimes(1);
    expect(compareMock).toHaveBeenCalledWith(
      PASSWORD,
      expect.stringMatching(BCRYPT_HASH_PATTERN)
    );
    expect(getActiveUserSubscriptionMock).not.toHaveBeenCalled();
  });

  it("returns null for a user without a password after one dummy-hash compare", async () => {
    // Arrange
    getUserByEmailMock.mockResolvedValue(userRow({ password: null }));

    // Act
    const authorizedUser = await runAuthorize({
      email: USER_EMAIL,
      password: PASSWORD,
    });

    // Assert
    expect(authorizedUser).toBeNull();
    expect(compareMock).toHaveBeenCalledTimes(1);
    expect(compareMock).toHaveBeenCalledWith(
      PASSWORD,
      expect.stringMatching(BCRYPT_HASH_PATTERN)
    );
    expect(getActiveUserSubscriptionMock).not.toHaveBeenCalled();
  });

  it("returns null for a wrong password without reading the subscription", async () => {
    // Arrange
    compareMock.mockResolvedValue(false);

    // Act
    const authorizedUser = await runAuthorize({
      email: USER_EMAIL,
      password: PASSWORD,
    });

    // Assert
    expect(authorizedUser).toBeNull();
    expect(compareMock).toHaveBeenCalledTimes(1);
    expect(compareMock).toHaveBeenCalledWith(PASSWORD, STORED_PASSWORD_HASH);
    expect(getActiveUserSubscriptionMock).not.toHaveBeenCalled();
  });

  it("returns the user with its claims for a correct password, no subscription", async () => {
    // Act
    const authorizedUser = await runAuthorize({
      email: USER_EMAIL,
      password: PASSWORD,
    });

    // Assert
    expect(authorizedUser).toEqual({
      id: USER_ID,
      email: USER_EMAIL,
      type: "regular",
      emailVerified: true,
      hasActiveSubscription: false,
      isTester: false,
    });
    expect(compareMock).toHaveBeenCalledTimes(1);
    expect(compareMock).toHaveBeenCalledWith(PASSWORD, STORED_PASSWORD_HASH);
    expect(getActiveUserSubscriptionMock).toHaveBeenCalledWith({
      userId: USER_ID,
    });
  });

  it("copies the claims from the user row and flags an active subscription", async () => {
    // Arrange
    getUserByEmailMock.mockResolvedValue(
      userRow({ emailVerified: false, isTester: true })
    );
    getActiveUserSubscriptionMock.mockResolvedValue({ id: "subscription-1" });

    // Act
    const authorizedUser = await runAuthorize({
      email: USER_EMAIL,
      password: PASSWORD,
    });

    // Assert
    expect(authorizedUser).toEqual({
      id: USER_ID,
      email: USER_EMAIL,
      type: "regular",
      emailVerified: false,
      hasActiveSubscription: true,
      isTester: true,
    });
  });

  it("looks the user up by the email exactly as typed and returns the stored email", async () => {
    // Arrange
    const typedEmail = "  User@Example.TEST";

    // Act
    const authorizedUser = await runAuthorize({
      email: typedEmail,
      password: PASSWORD,
    });

    // Assert
    expect(getUserByEmailMock).toHaveBeenCalledTimes(1);
    expect(getUserByEmailMock).toHaveBeenCalledWith(typedEmail);
    expect(authorizedUser?.email).toBe(USER_EMAIL);
  });
});
